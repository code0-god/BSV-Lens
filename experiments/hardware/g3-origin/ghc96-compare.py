#!/usr/bin/env python3
"""Strict metadata-only comparison of actual paired run03 outputs."""
import argparse
from collections import defaultdict
import hashlib
import json
from pathlib import Path
import re


EXCLUDED_ATTRIBUTES = {"src", "g3_emit_id", "g3_origin_ref"}
LEXER = re.compile(r"//[^\n]*|/\*[\s\S]*?\*/|\"(?:\\.|[^\"\\])*\"|\(\*[\s\S]*?\*\)|`(?:ifdef|ifndef|define|else|endif|undef|include)\b[^\n]*|\\\S+|(?:\d+)?'[sS]?[bBoOdDhH][0-9a-fA-F_xXzZ?]+|[A-Za-z_$][\w$]*|\d+|===|!==|>>>|<<<|==|!=|<=|>=|&&|\|\||<<|>>|\*\*|\+\+|--|\S")
ATTRIBUTE_PAIR = re.compile(r'\s*([A-Za-z_]\w*)\s*=\s*("(?:\\.|[^"\\])*")\s*(?:,|$)')


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def rtl_tokens(text):
    lines = text.splitlines(keepends=True)
    if len(lines) > 4 and lines[1].startswith("// Generated by Bluespec Compiler, version ") and lines[3].startswith("// On "):
        lines[3] = "// On <generation-time>\n"
    tokens = []
    removed = []
    for match in LEXER.finditer("".join(lines)):
        token = match.group()
        if token.startswith("(*"):
            body = token[2:-2]
            pairs = list(ATTRIBUTE_PAIR.finditer(body))
            if pairs and "".join(m.group() for m in pairs).strip() == body.strip():
                keys = [m[1] for m in pairs]
                if len(keys) == 2 and set(keys) == {"g3_emit_id", "g3_origin_ref"}:
                    removed.append({m[1]:json.loads(m[2]) for m in pairs})
                    continue
        tokens.append(token)
    return tokens, removed


def strip_attributes(value):
    if isinstance(value, list):
        return [strip_attributes(item) for item in value]
    if not isinstance(value, dict):
        return value
    result = {}
    for key,item in value.items():
        if key == "attributes":
            result[key] = {k:strip_attributes(v) for k,v in item.items() if k not in EXCLUDED_ATTRIBUTES}
        else:
            result[key] = strip_attributes(item)
    return result


def named_signature(name, item):
    return canonical({"visibleName":None if item["hide_name"] else name, "record":strip_attributes(item)})


def hardware_projection(model):
    result = strip_attributes(model)
    if not isinstance(result, dict):raise ValueError("netlist root must be an object")
    for module_name,module in result["modules"].items():
        # Formal port order is retained independently of JSON dictionary sorting.
        module["orderedPorts"] = list(module["ports"])
        for kind in ("cells", "netnames"):
            module[kind] = sorted(named_signature(name,item) for name,item in model["modules"][module_name][kind].items())
    return result


def object_bijection(before, after):
    if hardware_projection(before) != hardware_projection(after):
        raise ValueError("functional hardware projection differs")
    mappings = []
    for module_name,module in before["modules"].items():
        for kind in ("cells", "netnames"):
            left = defaultdict(list)
            right = defaultdict(list)
            for name,item in module[kind].items():left[named_signature(name,item)].append(name)
            for name,item in after["modules"][module_name][kind].items():right[named_signature(name,item)].append(name)
            if set(left) != set(right):raise ValueError("object signature mismatch")
            for signature in sorted(left):
                a,b = sorted(left[signature]),sorted(right[signature])
                if len(a) != len(b):raise ValueError("object multiplicity differs")
                for source,target in zip(a,b):
                    mappings.append({"module":module_name,"kind":kind,"before":source,"after":target,
                                     "completeRecordProjectionSha256":hashlib.sha256(signature.encode()).hexdigest()})
    return mappings


def compare(run, candidate="instrumented", noemit="instrumented-noemit"):
    base = Path(run)/"results"
    rows = []
    for label in "ABC":
        original = base/"baseline"/label
        patched = base/candidate/label
        disabled = base/noemit/label
        rtl = []
        names = sorted(p.name for p in (original/"rtl").glob("*.v"))
        if names != sorted(p.name for p in (patched/"rtl").glob("*.v")):
            raise ValueError("generated module file sets differ")
        for name in names:
            a,b,c = original/"rtl"/name, patched/"rtl"/name, disabled/"rtl"/name
            ta,ma = rtl_tokens(a.read_text());tb,mb = rtl_tokens(b.read_text());tc,mc = rtl_tokens(c.read_text())
            if not ta == tb == tc or ma or mc:raise ValueError("functional RTL tokens differ: "+label+"/"+name)
            rtl.append({"file":name,"baselineSha256":sha(a),"instrumentedSha256":sha(b),"noemitSha256":sha(c),
                        "functionalTokenSha256":hashlib.sha256(canonical(ta).encode()).hexdigest(),"removedInstrumentedAttributes":mb})
        a = json.loads((original/"design.json").read_text())
        b = json.loads((patched/"design.json").read_text())
        c = json.loads((disabled/"design.json").read_text())
        if a != c:raise ValueError("noemit entire JSON differs")
        if b != json.loads((patched/"capture-design.json").read_text()):raise ValueError("captured proc expansion changed JSON")
        mapping = object_bijection(a,b)
        rows.append({"fixture":label,"rtl":rtl,"baselineArtifactSha256":sha(original/"design.json"),
                     "instrumentedArtifactSha256":sha(patched/"design.json"),"noemitEntireJsonEqual":True,
                     "expandedProcEntireJsonEqual":True,"objectBijection":mapping,
                     "integerBitIdentity":"exact unchanged integers; no relaxed bit permutation",
                     "functionalProjectionSha256":hashlib.sha256(canonical(hardware_projection(a)).encode()).hexdigest()})
    return {"schema":"g3-noninterference-v1","verified":True,"originCorrectnessEstablished":False,
            "rtlExclusions":["BSC generation timestamp header field","exact two-field g3 metadata attribute blocks"],
            "netlistExclusions":{"attributes":sorted(EXCLUDED_ATTRIBUTES),"objectNames":"hide_name=1 only, explicit complete-record bijection"},
            "scope":"full generated functional RTL tokens and module/cell/port/ordered bits/parameters/constants/aliases, not counts",
            "rows":rows}


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--run",required=True,type=Path)
    p.add_argument("--candidate",default="instrumented")
    p.add_argument("--noemit",default="instrumented-noemit")
    p.add_argument("--output",required=True,type=Path)
    a = p.parse_args()
    result = compare(a.run,a.candidate,a.noemit)
    a.output.write_text(json.dumps(result,indent=2)+"\n")
    print(json.dumps({"verified":True,"fixtures":len(result["rows"]),"originCorrectnessEstablished":False}))
